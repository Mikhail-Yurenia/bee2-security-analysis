#include <stddef.h>
// Правильные пути для Bee2
#include "bee2/defs.h"
#include "bee2/math/zz.h"

// Генератор любого числа для CBMC
unsigned int __CPROVER_nondet_uint();

int main() {
    // Используем небольшие массивы для быстроты доказательства
    // Проверим сложение двух "больших" чисел из 2-х слов по 32 бита
    u32 a[2];
    u32 b[2];
    u32 r[2];

    // Заполняем символическими данными (любыми возможными числами)
    a[0] = (u32)__CPROVER_nondet_uint();
    a[1] = (u32)__CPROVER_nondet_uint();
    b[0] = (u32)__CPROVER_nondet_uint();
    b[1] = (u32)__CPROVER_nondet_uint();

    // Вызываем функцию из Bee2.
    // Мы доказываем, что она безопасна для ЛЮБЫХ входных a и b.
    zz_add(r, a, b, 2);

    // Это свойство CBMC должен доказать: что выполнение просто доходит до этой точки
    // без падений, переполнений или выхода за границы массива.
    __CPROVER_assert(1, "Safety Check");

    return 0;
}
